#!/usr/bin/env python3
"""Generate one combinational program ROM for memory A and the loader of B.

The assembler and the default game remain the Proyecto 2 baseline. This script
executes that assembler's assemble() function; it does not duplicate encoding.
The generated ROM contains constants and requires no power-on file loading.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import runpy
import sys


PROGRAM_WORDS = 128
DATA_WORDS = 16
NOP = "00000013"
OUTPUT_NAMES = ("asic_program_rom.v", "game.hex", "manifest.json")


def digest(data):
    return hashlib.sha256(data).hexdigest()


def source_label(path, root):
    """Stable provenance without leaking absolute workstation paths."""
    try:
        return path.relative_to(root).as_posix()
    except ValueError:
        return "external/" + path.name


def generate(root, source):
    assembler = root / "baseline/proyecto2/assembler/assemble.py"
    original_source = root / "baseline/proyecto2/assembler/game.s"
    source_bytes = source.read_bytes()
    assembler_bytes = assembler.read_bytes()
    # run_path executes this exact file with __name__='<run_path>'; its CLI is
    # not invoked and no bytecode cache is written into the immutable baseline.
    assemble = runpy.run_path(str(assembler))["assemble"]
    words = assemble(source_bytes.decode("utf-8"))
    if not 1 <= len(words) <= PROGRAM_WORDS:
        raise ValueError(f"Program must contain 1..{PROGRAM_WORDS} words; got {len(words)}")
    if not all(re.fullmatch(r"[0-9a-f]{8}", word) for word in words):
        raise ValueError("Assembler returned a noncanonical 32-bit hexadecimal word")
    hex_bytes = ("\n".join(words) + "\n").encode("ascii")
    if source == original_source.resolve():
        if len(words) != 94:
            raise ValueError("The unchanged baseline game must contain exactly 94 words")
        for reference in (root / "baseline/proyecto2/assembler/game.hex",
                          root / "baseline/proyecto2/pochoco_soc-main/sw/game.hex"):
            if reference.read_bytes() != hex_bytes:
                raise ValueError(f"Baseline game does not match {source_label(reference, root)}")

    source_sha = digest(source_bytes)
    lines = [
        "// Copyright 2026 Universidad de los Andes.",
        "// SPDX-License-Identifier: SHL-0.51",
        "// Generated by scripts/generate_asic_memory.py. Do not edit by hand.",
        f"// Source SHA256: {source_sha}",
        f"// {len(words)} program words; {PROGRAM_WORDS - len(words)} reserved words return NOP.",
        "module asic_program_rom (",
        "  input  wire [6:0]  word_index_i,",
        "  output wire [31:0] word_o",
        ");",
        "  function [31:0] rom_word;",
        "    input [6:0] index;",
        "    begin",
        "      case (index)",
    ]
    lines.extend(f"        7'd{index}: rom_word = 32'h{word};" for index, word in enumerate(words))
    lines.extend([
        f"        default: rom_word = 32'h{NOP};",
        "      endcase",
        "    end",
        "  endfunction",
        "  assign word_o = rom_word(word_index_i);",
        "endmodule",
        "",
    ])
    verilog_bytes = "\n".join(lines).encode("utf-8")
    manifest = {
        "schema_version": 1,
        "source": {"path": source_label(source, root), "sha256": source_sha},
        "assembler": {"path": source_label(assembler, root), "sha256": digest(assembler_bytes)},
        "program_words": len(words),
        "program_bytes": len(words) * 4,
        "program_capacity_words": PROGRAM_WORDS,
        "reserved_program_words": PROGRAM_WORDS - len(words),
        "data_capacity_words": DATA_WORDS,
        "unified_capacity_words": PROGRAM_WORDS + DATA_WORDS,
        "program_padding_word": NOP,
        "data_boot_word": "00000000",
        "memory_map": {
            "word_bytes": 4,
            "program_byte_start": 0,
            "program_byte_end_inclusive": PROGRAM_WORDS * 4 - 1,
            "data_byte_start": PROGRAM_WORDS * 4,
            "data_byte_end_inclusive": (PROGRAM_WORDS + DATA_WORDS) * 4 - 1,
        },
        "program_hex_sha256": digest(hex_bytes),
        "rom_verilog_sha256": digest(verilog_bytes),
    }
    return {
        "asic_program_rom.v": verilog_bytes,
        "game.hex": hex_bytes,
        "manifest.json": (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode("utf-8"),
    }


def main():
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=root / "baseline/proyecto2/assembler/game.s")
    parser.add_argument("--output-dir", type=Path, default=root / "rtl/asic/generated")
    parser.add_argument("--check", action="store_true", help="Compare all three outputs byte-for-byte without writing")
    args = parser.parse_args()
    try:
        source = args.source.expanduser().resolve(strict=True)
        output = args.output_dir.expanduser().resolve()
        # Keep the FPGA baseline and the separate original repository immutable
        # even if a caller accidentally selects either as the output directory.
        for protected in (root / "baseline", root.parent / "Proyecto 2"):
            if output.is_relative_to(protected.resolve()):
                raise ValueError("Output directory must not be inside the baseline or original Proyecto 2")
        if source in [output / name for name in OUTPUT_NAMES]:
            raise ValueError("Output files must not overwrite the input source")
        files = generate(root, source)
        if args.check:
            mismatches = [name for name, data in files.items()
                          if not (output / name).is_file() or (output / name).read_bytes() != data]
            if mismatches:
                raise ValueError("Generated files missing or stale: " + ", ".join(mismatches))
            action = "checked"
        else:
            # All inputs have been validated before creating/writing outputs.
            # Write manifest last; --check catches any incomplete generation.
            output.mkdir(parents=True, exist_ok=True)
            for name in OUTPUT_NAMES:
                path = output / name
                if not path.is_file() or path.read_bytes() != files[name]:
                    path.write_bytes(files[name])
            action = "generated"
        count = json.loads(files["manifest.json"])["program_words"]
        print(f"PASS {action}: {count} words, ROM {PROGRAM_WORDS}, data {DATA_WORDS}; {output}")
    except (OSError, UnicodeError, ValueError, KeyError) as error:
        raise SystemExit(f"Memory generation failed: {error}")


if __name__ == "__main__":
    main()
